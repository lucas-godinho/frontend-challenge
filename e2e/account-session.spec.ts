test('an expired session closes private profile access and preserves the route for login', async ({ page, isMobile }) => {
  await page.setViewportSize({ width: isMobile ? 390 : 1440, height: isMobile ? 844 : 1000 })
  await page.goto('/login?returnTo=%2Fprofile')
  await page.getByLabel('E-mail').fill('ana@kurio.test')
  await page.locator('#account-password').fill('Kurio123!')
  await page.locator('form').getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/profile$/)
  await page.evaluate(() => {
    const key = 'kurio:mock-session:v1'
    const session = JSON.parse(localStorage.getItem(key) ?? '{}')
    localStorage.setItem(key, JSON.stringify({ ...session, expiresAt: '2000-01-01T00:00:00.000Z' }))
  })
  await page.reload()

  if (isMobile) {
    await expect(page).toHaveURL(/\/login\?returnTo=%2Fprofile/)
    await expect(page.locator('.auth-page.is-screen')).toBeVisible()
  } else {
    await expect(page).toHaveURL(/\/profile$/)
    await expect(page.locator('.auth-page.is-dialog')).toBeVisible()
  }
})

test('guest cart merges on login while favorites and cart stay isolated when accounts change', async ({ page }) => {
  test.setTimeout(60_000)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/nft/orbital-01')
  const cartAdded = page.waitForResponse((response) => response.request().method() === 'POST' && response.url().endsWith('/api/cart/items'))
  await page.getByRole('button', { name: 'Adicionar ao carrinho' }).click()
  expect((await cartAdded).status()).toBe(201)
  const navigationOrigin = await page.evaluate(() => performance.timeOrigin)
  await page.getByRole('button', { name: 'Entre para favoritar Orbital Bloom #01' }).click()
  await expect(page).toHaveURL(/\/login\?returnTo=/)
  expect(await page.evaluate(() => performance.timeOrigin)).toBe(navigationOrigin)
  await page.getByLabel('E-mail').fill('ana@kurio.test')
  await page.locator('#account-password').fill('Kurio123!')
  await page.locator('form').getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/nft\/orbital-01$/)
  const favoriteAdded = page.waitForResponse((response) => response.request().method() === 'POST' && response.url().endsWith('/api/favorites'))
  await page.getByRole('button', { name: 'Adicionar Orbital Bloom #01 aos favoritos' }).click()
  expect((await favoriteAdded).status()).toBe(200)
  await page.goto('/favorites')
  await expect(page.getByRole('heading', { name: 'Orbital Bloom #01' })).toBeVisible()
  await page.goto('/cart')
  await expect(page.getByRole('heading', { name: 'Orbital Bloom #01' })).toBeVisible()
  await expect(cartQuantity(page, 'Orbital Bloom #01')).toHaveText('1')
  await page.goto('/profile')
  await page.getByRole('button', { name: 'Sair' }).click()
  await expect(page).toHaveURL(/\/\?sort=recent&page=1$/)
  await page.goto('/login?returnTo=%2Ffavorites')
  await page.getByLabel('E-mail').fill('rafael@kurio.test')
  await page.locator('#account-password').fill('Kurio123!')
  await page.locator('form').getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/favorites$/)
  await expect(page.getByRole('heading', { name: 'Sua lista está vazia' })).toBeVisible()
  await page.goto('/cart')
  await expect(page.getByRole('heading', { name: 'Seu carrinho está vazio' })).toBeVisible()
})

test('an expired identity cannot read its private cart before the session query runs', async ({ page }) => {
  const initialized = page.waitForResponse((response) => response.url().endsWith('/api/session'))
  await page.goto('/login')
  await initialized
  const cart = await page.evaluate(async () => {
    localStorage.setItem('kurio:mock-session:v1', JSON.stringify({ userId: 'collector-ana', expiresAt: '2000-01-01T00:00:00Z' }))
    localStorage.setItem('kurio:mock-cart:user:collector-ana', JSON.stringify([{ nftId: 'orbital-01', quantity: 3 }]))
    localStorage.setItem('kurio:mock-cart:v1', JSON.stringify([{ nftId: 'blue-hour-03', quantity: 1 }]))
    return (await fetch('/api/cart')).json()
  })
  expect(cart.items.map((item: { nft: { id: string } }) => item.nft.id)).toEqual(['blue-hour-03'])
  await page.goto('/cart')
  await expect(page.getByRole('heading', { name: 'Blue Hour #03' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Orbital Bloom #01' })).toHaveCount(0)
})
