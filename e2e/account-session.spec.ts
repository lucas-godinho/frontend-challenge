import { expect, test } from '@playwright/test'
import { cartQuantity } from './support/selectors'

test('private favorites return to their original route after login and the session survives refresh', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/favorites')
  await expect(page).toHaveURL(/\/login\?returnTo=%2Ffavorites/)
  await page.getByLabel('E-mail').fill('ana@kurio.test')
  await page.locator('#account-password').fill('Kurio123!')
  await page.locator('form').getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/favorites$/)
  await expect(page.getByRole('heading', { name: 'Favoritos' })).toBeVisible()
  await page.goto('/profile')
  await expect(page.getByRole('heading', { name: 'Perfil do colecionador' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Perfil do colecionador' })).toBeVisible()
})

test('registration validates confirmation, reports duplicate email, and creates a persistent session', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/register')
  await page.getByLabel('Nome de usuário').fill('Colecionador Novo')
  await page.getByLabel('E-mail').fill('ana@kurio.test')
  await page.locator('#account-password').fill('SenhaNova123!')
  await page.getByLabel('Confirmar senha').fill('diferente')
  await page.locator('form').getByRole('button', { name: 'Criar minha conta' }).click()
  await expect(page.getByText('As senhas não coincidem.')).toBeVisible()
  await page.getByLabel('Confirmar senha').fill('SenhaNova123!')
  await page.locator('form').getByRole('button', { name: 'Criar minha conta' }).click()
  await expect(page.getByRole('alert')).toContainText('Este e-mail já possui uma conta.')
  await page.getByLabel('E-mail').fill('novo@kurio.test')
  await page.locator('form').getByRole('button', { name: 'Criar minha conta' }).click()
  await expect(page).toHaveURL(/\/profile$/)
  await expect(page.getByRole('heading', { name: 'Perfil do colecionador' })).toBeVisible()
  const storedAccount = await page.evaluate(() => JSON.parse(localStorage.getItem('kurio:mock-users:v1') ?? '[]')[0])
  expect(storedAccount.password).toBeUndefined()
  expect(storedAccount.passwordDigest).toMatch(/^[a-f0-9]{64}$/)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Perfil do colecionador' })).toBeVisible()
})

