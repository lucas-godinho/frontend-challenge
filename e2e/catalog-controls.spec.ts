import { expect, test } from '@playwright/test'
import { queryCatalog } from '../src/mocks/catalog'
import { catalogFixture } from '../src/mocks/fixtures'

test('catalog inventory counts, combined filters and pagination remain consistent', () => {
  const all = queryCatalog({})
  expect(all.total).toBe(54)
  expect(all.facets.categories.reduce((sum, facet) => sum + facet.count, 0)).toBe(all.total)
  expect(all.facets.networks.reduce((sum, facet) => sum + facet.count, 0)).toBe(all.total)
  for (const facet of all.facets.categories) expect(queryCatalog({ category: facet.value }).total).toBe(facet.count)
  const ids = Array.from({ length: 6 }, (_, index) => queryCatalog({ page: index + 1 }).items.map((nft) => nft.id)).flat()
  expect(new Set(ids).size).toBe(all.total)
  const result = queryCatalog({ category: 'art', network: 'Ethereum', minPrice: 0.5, maxPrice: 5, sort: 'price-asc' })
  const expected = catalogFixture.filter((nft) => nft.category === 'art' && nft.network === 'Ethereum' && Number(nft.priceEth) >= 0.5 && Number(nft.priceEth) <= 5)
  expect(result.total).toBe(expected.length)
  expect(result.items.every((nft) => expected.some((item) => item.id === nft.id))).toBeTruthy()
  expect(queryCatalog({ page: 999 }).page).toBe(6)
  expect(queryCatalog({ q: 'no-matching-work' }).total).toBe(0)
})

test('desktop filters preserve scroll and restore price through browser history', async ({ page }, info) => {
  test.skip(info.project.name.includes('mobile'), 'Sidebar belongs to desktop layout')
  await page.goto('/')
  await page.evaluate(() => window.scrollTo({ top: 300, behavior: 'instant' }))
  const category = page.getByRole('button', { name: 'Fotografia (6)', exact: true })
  const before = await page.evaluate(() => window.scrollY)
  await category.click()
  await expect(page.locator('.catalog-results')).toHaveAttribute('aria-busy', 'false')
  await expect(page.locator('.nft-grid .nft-card-link')).toHaveCount(6)
  expect(Math.abs(await page.evaluate(() => window.scrollY) - before)).toBeLessThan(5)
  await category.click()
  await expect(page.locator('.nft-grid .nft-card-link')).toHaveCount(9)
  const minimum = page.getByRole('slider', { name: 'Preço mínimo', exact: true })
  await minimum.focus()
  await minimum.press('ArrowRight')
  await minimum.press('ArrowRight')
  await page.getByRole('button', { name: 'Aplicar', exact: true }).click()
  await expect(page).toHaveURL(/minPrice=0\.04/)
  await page.goBack()
  await expect(minimum).toHaveValue('0.02')
  await expect(page.getByRole('region', { name: 'NFT em destaque', exact: true })).toBeVisible()
})

test('custom sort supports keyboard and pagination works after sorting', async ({ page }) => {
  await page.goto('/')
  const sort = page.getByRole('combobox', { name: 'Ordenar NFTs' }).filter({ visible: true })
  await sort.click()
  await sort.press('End')
  await sort.press('Enter')
  await expect(page).toHaveURL(/sort=price-desc/)
  await expect(page.locator('.catalog-results')).toHaveAttribute('aria-busy', 'false')
  const first = await page.locator('.nft-grid .nft-card-link').first().getAttribute('href')
  await page.getByRole('button', { name: 'Página 2', exact: true }).click()
  await expect(page).toHaveURL(/page=2/)
  await expect(page.locator('.catalog-results')).toHaveAttribute('aria-busy', 'false')
  expect(await page.locator('.nft-grid .nft-card-link').first().getAttribute('href')).not.toBe(first)
  await expect(page.getByRole('button', { name: 'Página 2', exact: true })).toHaveAttribute('aria-current', 'page')
})
